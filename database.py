def check_in_booking(booking_id, admin_username):
    connection = get_connection()

    try:
        if USE_SUPABASE:
            connection.execute("BEGIN")

            booking = connection.execute("""
                SELECT *
                FROM bookings
                WHERE id = ?
                FOR UPDATE
            """, (booking_id,)).fetchone()

        else:
            connection.execute("BEGIN IMMEDIATE")

            booking = connection.execute("""
                SELECT *
                FROM bookings
                WHERE id = ?
            """, (booking_id,)).fetchone()

        if booking is None:
            connection.rollback()
            return "not_found"

        if booking["status"] != "Confirmed":
            connection.rollback()
            return "cancelled"

        if booking["checked_in_at"] is not None:
            connection.rollback()
            return "already_checked_in"

        cursor = connection.execute("""
            UPDATE bookings
            SET checked_in_at = CURRENT_TIMESTAMP,
                checked_in_by = ?
            WHERE id = ?
              AND status = 'Confirmed'
              AND checked_in_at IS NULL
        """, (admin_username, booking_id))

        if cursor.rowcount == 0:
            connection.rollback()
            return "already_checked_in"

        connection.commit()
        return "success"

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


def book_slot(slot_number, customer_name, vehicle_number, customer_id=None):
    connection = get_connection()

    try:
        cursor = connection.cursor()

        cursor.execute("""
            UPDATE parking_slots
            SET status = 'Occupied'
            WHERE slot_number = ? AND status = 'Available'
        """, (slot_number,))

        if cursor.rowcount == 0:
            connection.rollback()
            return False

        qr_token = secrets.token_urlsafe(32)

        connection.execute("""
            INSERT INTO bookings
            (slot_number, customer_name, vehicle_number, customer_id, qr_token)
            VALUES (?, ?, ?, ?, ?)
        """, (
            slot_number,
            customer_name,
            vehicle_number,
            customer_id,
            qr_token
        ))

        if customer_id is not None:
            record_customer_activity(
                connection,
                customer_id,
                "Booking",
                f"Reserved parking slot {slot_number} for vehicle {vehicle_number}."
            )

        connection.commit()
        return True

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


def cancel_booking(booking_id, customer_id=None):
    connection = get_connection()

    try:
        if USE_SUPABASE:
            connection.execute("BEGIN")
        else:
            connection.execute("BEGIN IMMEDIATE")

        if customer_id is None:
            booking = connection.execute("""
                SELECT slot_number, status, customer_id, vehicle_number
                FROM bookings
                WHERE id = ?
            """, (booking_id,)).fetchone()
        else:
            booking = connection.execute("""
                SELECT slot_number, status, customer_id, vehicle_number
                FROM bookings
                WHERE id = ? AND customer_id = ?
            """, (booking_id, customer_id)).fetchone()

        if booking is None or booking["status"] != "Confirmed":
            connection.rollback()
            return False

        connection.execute("""
            UPDATE parking_slots
            SET status = 'Available'
            WHERE slot_number = ?
        """, (booking["slot_number"],))

        connection.execute("""
            UPDATE bookings
            SET status = 'Cancelled'
            WHERE id = ?
        """, (booking_id,))

        if booking["customer_id"] is not None:
            record_customer_activity(
                connection,
                booking["customer_id"],
                "Cancellation",
                f"Cancelled booking for slot {booking['slot_number']}."
            )

        connection.commit()
        return True

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


