USE_SUPABASE = os.getenv("USE_SUPABASE", "false").lower() == "true"


class HybridRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


class CursorAdapter:
    def __init__(self, cursor, is_postgres):
        self.cursor = cursor
        self.is_postgres = is_postgres

    def execute(self, query, parameters=()):
        if self.is_postgres:
            query = query.replace("?", "%s")
        self.cursor.execute(query, parameters)
        return self

    @property
    def rowcount(self):
        return self.cursor.rowcount

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()


class ConnectionAdapter:
    def __init__(self, connection, is_postgres):
        self.connection = connection
        self.is_postgres = is_postgres

    def cursor(self):
        return CursorAdapter(self.connection.cursor(), self.is_postgres)

    def execute(self, query, parameters=()):
        if self.is_postgres:
            query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def get_connection():
    if USE_SUPABASE:
        import psycopg
        from psycopg.rows import class_row

        connection = psycopg.connect(
            os.environ["DATABASE_URL"],
            row_factory=class_row(HybridRow),
            connect_timeout=15
        )
        return ConnectionAdapter(connection, True)

    connection = sqlite3.connect(DATABASE, timeout=10)
    connection.row_factory = sqlite3.Row
    return ConnectionAdapter(connection, False)


